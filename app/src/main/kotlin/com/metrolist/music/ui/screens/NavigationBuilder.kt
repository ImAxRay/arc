@OptIn(ExperimentalMaterial3Api::class)
fun NavGraphBuilder.navigationBuilder(
    navController: NavHostController,
    scrollBehavior: TopAppBarScrollBehavior,
    latestVersionName: String,
    activity: Activity,
    snackbarHostState: SnackbarHostState,
) {
    composable(Screens.Home.route) {
        HomeScreen(snackbarHostState = snackbarHostState)
    }

    composable(Screens.Search.route) { backStackEntry ->
        val pureBlackEnabled by rememberPreference(PureBlackKey, defaultValue = false)
        val darkTheme by rememberEnumPreference(DarkModeKey, defaultValue = DarkMode.AUTO)
        val isSystemInDarkTheme = isSystemInDarkTheme()
        val useDarkTheme =
            remember(darkTheme, isSystemInDarkTheme) {
                if (darkTheme == DarkMode.AUTO) isSystemInDarkTheme else darkTheme == DarkMode.ON
            }
        val pureBlack =
            remember(pureBlackEnabled, useDarkTheme) {
                pureBlackEnabled && useDarkTheme
            }
        SearchScreen(
            pureBlack = pureBlack,
            savedStateHandle = backStackEntry.savedStateHandle
        )
    }

    composable(Screens.Library.route) {
        LibraryScreen()
    }

    composable(Screens.ListenTogether.route) {
        ListenTogetherScreen(navController, showTopBar = false)
    }

    composable(
        route = "listen_together_from_topbar",
    ) {
        ListenTogetherScreen(navController, showTopBar = true)
    }

    composable("history") {
        HistoryScreen(navController)
    }

    composable("stats") {
        StatsScreen(navController)
    }

    composable("mood_and_genres") {
        MoodAndGenresScreen(navController)
    }

    composable("account") {
        AccountScreen(navController)
    }

    composable("new_release") {
        NewReleaseScreen(navController)
    }

    composable("release_radar") {
        com.metrolist.music.arc.ReleaseRadarScreen(navController)
    }

    composable("charts_screen") {
        ChartsScreen(navController)
    }

    composable(
        route = "browse/{browseId}",
        arguments =
            listOf(
                navArgument("browseId") {
                    type = NavType.StringType
                },
            ),
    ) {
        BrowseScreen(
            navController,
            it.arguments?.getString("browseId"),
        )
    }

    composable(
        route = "search/{query}",
        arguments =
            listOf(
                navArgument("query") {
                    type = NavType.StringType
                },
            ),
        enterTransition = {
            fadeIn(tween(250))
        },
        exitTransition = {
            if (targetState.destination.route?.startsWith("search/") == true) {
                fadeOut(tween(200))
            } else {
                fadeOut(tween(200)) + slideOutHorizontally { -it / 2 }
            }
        },
        popEnterTransition = {
            if (initialState.destination.route?.startsWith("search/") == true) {
                fadeIn(tween(250))
            } else {
                fadeIn(tween(250)) + slideInHorizontally { -it / 2 }
            }
        },
        popExitTransition = {
            fadeOut(tween(200))
        },
    ) { backStackEntry ->
        OnlineSearchResult(
            savedStateHandle = backStackEntry.savedStateHandle
        )

    }

    composable(
        route = "album/{albumId}",
        arguments =
            listOf(
                navArgument("albumId") {
                    type = NavType.StringType
                },
            ),
    ) {
        AlbumScreen(navController)
    }

    composable(
        route = "artist/{artistId}?isPodcastChannel={isPodcastChannel}",
        arguments =
            listOf(
                navArgument("artistId") {
                    type = NavType.StringType
                },
                navArgument("isPodcastChannel") {
                    type = NavType.BoolType
                    defaultValue = false
                },
            ),
    ) {
        ArtistScreen(navController)
    }

    composable(
        route = "artist/{artistId}/songs",
        arguments =
            listOf(
                navArgument("artistId") {
                    type = NavType.StringType
                },
            ),
    ) {
        ArtistSongsScreen(navController)
    }

    composable(
        route = "artist/{artistId}/albums",
        arguments =
            listOf(
                navArgument("artistId") {
                    type = NavType.StringType
                },
            ),
    ) {
        ArtistAlbumsScreen(navController, scrollBehavior)
    }

    composable(
        route = "artist/{artistId}/items?browseId={browseId}?params={params}",
        arguments =
            listOf(
                navArgument("artistId") {
                    type = NavType.StringType
                },
                navArgument("browseId") {
                    type = NavType.StringType
                    nullable = true
                },
                navArgument("params") {
                    type = NavType.StringType
                    nullable = true
                },
            ),
    ) {
        ArtistItemsScreen(navController)
    }

    composable(
        route = "online_playlist/{playlistId}",
        arguments =
            listOf(
                navArgument("playlistId") {
                    type = NavType.StringType
                },
            ),
    ) {
        OnlinePlaylistScreen(navController)
    }

    composable(
        route = "online_podcast/{podcastId}",
        arguments =
            listOf(
                navArgument("podcastId") {
                    type = NavType.StringType
                },
            ),
    ) {
        OnlinePodcastScreen(navController, scrollBehavior)
    }

    composable(
        route = "local_playlist/{playlistId}",
        arguments =
            listOf(
                navArgument("playlistId") {
                    type = NavType.StringType
                },
            ),
    ) {
        LocalPlaylistScreen(navController)
    }

    composable(
        route = "auto_playlist/{playlist}",
        arguments =
            listOf(
                navArgument("playlist") {
                    type = NavType.StringType
                },
            ),
    ) {
        AutoPlaylistScreen(navController)
    }

    composable(
        route = "cache_playlist/{playlist}",
        arguments =
            listOf(
                navArgument("playlist") {
                    type = NavType.StringType
                },
            ),
    ) {
        CachePlaylistScreen(navController)
    }

    composable(
        route = "top_playlist/{top}",
        arguments =
            listOf(
                navArgument("top") {
                    type = NavType.StringType
                },
            ),
    ) {
        TopPlaylistScreen(navController)
    }

    composable(
        route = "youtube_browse/{browseId}?params={params}",
        arguments =
            listOf(
                navArgument("browseId") {
                    type = NavType.StringType
                    nullable = true
                },
                navArgument("params") {
                    type = NavType.StringType
                    nullable = true
                },
            ),
    ) {
        YouTubeBrowseScreen(navController)
    }

    composable("settings") {
        com.metrolist.music.arc.WithScrollSections {
            SettingsScreen(navController, latestVersionName)
        }
    }

    composable("settings/visual") {
        com.metrolist.music.arc.WithScrollSections {
            com.metrolist.music.arc.VisualSettings(navController)
        }
    }

    composable("settings/appearance") {
        com.metrolist.music.arc.WithScrollSections {
            AppearanceSettings(navController, snackbarHostState)
        }
    }

    composable("settings/appearance/theme") {
        com.metrolist.music.arc.WithScrollSections {
            ThemeScreen(navController)
        }
    }

    composable("settings/content") {
        com.metrolist.music.arc.WithScrollSections {
            ContentSettings(navController)
        }
    }

    composable("settings/content/romanization") {
        com.metrolist.music.arc.WithScrollSections {
            RomanizationSettings(navController)
        }
    }

    composable("settings/ai") {
        com.metrolist.music.arc.WithScrollSections {
            AiSettings(navController)
        }
    }

    composable("arc/triage") {
        com.metrolist.music.arc.SongTriageScreen(navController)
    }

    composable("arc/ignored") {
        com.metrolist.music.arc.IgnoredScreen(navController)
    }

    composable("arc/left_out") {
        com.metrolist.music.arc.LeftOutScreen(navController)
    }

    composable("settings/sound") {
        com.metrolist.music.arc.WithScrollSections {
            PlayerSettings(navController, "sound")
        }
    }

    composable("settings/queue") {
        com.metrolist.music.arc.WithScrollSections {
            PlayerSettings(navController, "queue")
        }
    }

    composable("settings/region") {
        com.metrolist.music.arc.WithScrollSections {
            ContentSettings(navController, "region")
        }
    }

    composable("settings/lyrics") {
        com.metrolist.music.arc.WithScrollSections {
            ContentSettings(navController, "lyrics")
        }
    }

    composable("settings/library") {
        com.metrolist.music.arc.WithScrollSections {
            ContentSettings(navController, "library")
        }
    }

    composable("settings/drive") {
        com.metrolist.music.arc.WithScrollSections {
            com.metrolist.music.ui.screens.settings.DriveSettings(navController)
        }
    }

    composable("settings/untitled") {
        com.metrolist.music.arc.WithScrollSections {
            com.metrolist.music.ui.screens.settings.UntitledSettings(navController)
        }
    }

    composable("settings/addons") {
        com.metrolist.music.arc.WithScrollSections {
            com.metrolist.music.ui.screens.settings.AddonsSettings(navController)
        }
    }

    composable("settings/storage") {
        com.metrolist.music.arc.WithScrollSections {
            StorageSettings(navController)
        }
    }

    composable("settings/privacy") {
        com.metrolist.music.arc.WithScrollSections {
            PrivacySettings(navController)
        }
    }

    composable("settings/backup_restore") {
        com.metrolist.music.arc.WithScrollSections {
            BackupAndRestore(navController)
        }
    }

    composable("settings/integrations") {
        com.metrolist.music.arc.WithScrollSections {
            IntegrationScreen(navController)
        }
    }

    composable("settings/integrations/discord") {
        com.metrolist.music.arc.WithScrollSections {
            DiscordSettings(navController)
        }
    }

    composable("settings/integrations/lastfm") {
        com.metrolist.music.arc.WithScrollSections {
            LastFMSettings(navController)
        }
    }

    composable(route = "settings/integrations/listen_together") {
        ListenTogetherSettings(navController)
    }

    composable("settings/updater") {
        com.metrolist.music.arc.WithScrollSections {
            UpdaterScreen(navController)
        }
    }

    composable("login") {
        LoginScreen(navController)
    }

    composable("switch_channel") {
        LoginScreen(
            navController = navController,
            isSwitchingChannel = true,
        )
    }

    composable("wrapped") {
        WrappedScreen()
    }

    composable("arc_artist_albums/{artistId}/{title}") { entry ->
        com.metrolist.music.arc.ArtistAlbumsWindow(
            navController = navController,
            artistId = entry.arguments?.getString("artistId").orEmpty(),
            sectionTitle = entry.arguments?.getString("title").orEmpty(),
        )
    }

    composable("equalizer") {
        EqScreen()
    }

    composable("eq_wizard") {
        WizardScreen(onNavigateBack = {
            navController.popBackStack()
        })
    }

    composable(
        route = "recognition?autoStart={autoStart}",
        arguments =
            listOf(
                navArgument("autoStart") {
                    type = NavType.BoolType
                    defaultValue = false
                },
            ),
    ) {
        RecognitionScreen(navController, it.arguments?.getBoolean("autoStart") ?: false)
    }

    composable("recognition_history") {
        RecognitionHistoryScreen(navController)
    }
    composable("settings/android_auto") {
        com.metrolist.music.arc.WithScrollSections {
            AndroidAutoSettings(navController)
        }
    }
}
